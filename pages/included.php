          <h2>The differences between the three</h2>
          <h3>Goa &mdash; $1,290</h3>
          <p>Two meals a day rather than three; lunch is on you, and there are
            eleven beach shacks within ten minutes. Airport transfer is not
            included but we will book a taxi if you send a flight number.
            Sharing is standard; a room to yourself is $280 more.</p>
          <h3>Rishikesh &mdash; $1,150</h3>
          <p>Three meals a day, all at the guesthouse, all included. Single
            rooms as standard at no extra cost, because the rooms are small
            singles. The shared car from Delhi airport is $45 and is the one
            thing most people add.</p>
          <h3>Bali &mdash; $1,540</h3>
          <p>Two meals a day, and the group minibus from Denpasar at 14:00 on
            the arrival day is included. Sharing is standard; a bungalow to
            yourself is $340 more. This is the most expensive of the three
            because it has two teaching sessions a day and the flights make it
            the longest trip anybody does.</p>
        </div>
        <div class="prose">
          <h2>What the excursion is</h2>
          <p>One afternoon in the middle of each week, included, and genuinely
            optional. In Goa it is a boat out at dusk. In Rishikesh it is a walk
            up to a waterfall that takes about three hours and is steeper than
            it sounds. In Bali it is the salt flats at Kusamba, which is
            forty minutes away and is the least yoga-adjacent thing we do.</p>
          <h2>Insurance, which is not optional</h2>
          <p>You must have travel insurance that covers medical treatment and
            repatriation in the country you are travelling to, and we will ask
            for the policy number before the balance is due. This is not
            bureaucracy: a medical evacuation from Amed is genuinely expensive
            and people have needed one.</p>
          <p>Check that your policy covers yoga. Most do. A few exclude
            &ldquo;adventure activities&rdquo; in terms broad enough to catch
            it, and it is worth two minutes to find out.</p>
          <h2>Paying</h2>
          <p>A $300 deposit holds a place and is fully refundable for fourteen
            days. The balance is due eight weeks before departure. Bank transfer
            in sterling, euros or dollars; we absorb the conversion. There is no
            deposit scheme, no instalment plan with interest on it, and no third
            party involved in the payment.</p>
        </div>
      </div>
    </div>
