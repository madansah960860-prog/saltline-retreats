        <h2>Cancellation, both directions</h2>
        <p>If you cancel more than eight weeks before departure you lose the
          $300 deposit and nothing else. Between eight and four weeks we keep
          50% of the total. Inside four weeks we keep the lot, because by then
          the room is paid for and the food is bought. This is why insurance
          matters.</p>
        <p>If <em>we</em> cancel &mdash; which has happened twice, once for a
          cyclone and once when Tess broke a wrist &mdash; you get everything
          back, including the deposit, within fourteen days. We do not offer a
          credit note instead of a refund and we never will.</p>
