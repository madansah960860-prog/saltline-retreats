        <div class="prose">
          <h2>How it started</h2>
          <p>Tess Marlowe taught in Brighton for nine years and took eleven
            people to Goa in February 2018 because a student asked her to. It
            was meant to be one week. The guesthouse asked her to come back, and
            then somebody who had been on it asked whether she would do the same
            thing in Rishikesh, where she had studied in 2014.</p>
          <p>Bali came in 2019, the three-a-year pattern settled in 2022 after
            two years of not running anything, and it has not changed since.
            There is no plan to add a fourth.</p>

          <h2>Why only three</h2>
          <p>Because Tess teaches every morning session on every retreat, and
            one person can do about three weeks a year of that properly. The
            obvious way to grow would be to hire teachers and run eight, and it
            is the thing we are asked about most often by people in the
            business.</p>
          <p>The reason we do not is that the three partners we work with
            &mdash; a family in Ashwem, a guesthouse in Tapovan, two sisters in
            Amed &mdash; are the actual product. They have run these weeks with
            us for years, they know what a group of twelve needs at six in the
            morning, and none of that is transferable to a fourth place chosen
            because it would sell.</p>
        </div>
        <div class="prose">
          <h2>What we pay people</h2>
          <p>Our partners set their own price and we pay it. We do not negotiate
            rates down, we pay in full before the group arrives rather than
            after, and we have paid in full for both retreats we have cancelled.
            Around 58% of what you pay goes directly to the guesthouse, the
            kitchen and the drivers in the country you are visiting.</p>
          <p>We publish that number because retreat pricing is opaque and
            because a $1,290 week in India is a lot of money that ought to be
            mostly going somewhere useful.</p>

          <h2>What we are not</h2>
          <p>Not a wellness brand, not a booking platform, and not a company
            that will sell you a flight. There is no membership, no app, no
            newsletter and no teacher training. We have turned down two offers
            to list these retreats on aggregator sites, because the commission
            would have to come out of either your price or the guesthouse's, and
            neither is acceptable.</p>
          <p>This website carries display advertising, which covers the cost of
            running it. No advertiser has any say in anything written here &mdash;
            see the
            <a href="../policies/advertising-disclosure.php">advertising
            disclosure</a>.</p>

          <h2>Carbon, briefly and honestly</h2>
          <p>Long-haul flights are the overwhelming majority of the footprint of
            any retreat like this, and nothing we do on the ground meaningfully
            offsets that. We are not going to pretend otherwise with a badge.
            What we do instead: three retreats rather than eight, seven and
            eight nights rather than four, and no encouragement to do more than
            one a year.</p>
        </div>
