        <h2>The forty-one steps</h2>
        <p>The guesthouse is up a steep stone path from the road with forty-one steps in it, and there is no way around them. Bags are carried up for you on the first day. If stairs are a genuine problem this is not the retreat to choose, and we would rather say that plainly here than have you find out in March.</p>
        <h2>Tapovan and the other bank</h2>
        <p>We stay on the quieter east side, above the river. Laxman Jhula and the cafes are a fifteen-minute walk and a footbridge away. Rishikesh is a working pilgrimage town rather than a resort: there are cows in the road, there is traffic, and the evening aarti at Triveni Ghat is genuinely worth the trip across even though it is crowded.</p>
        <h2>Dry, and what that means</h2>
        <p>Alcohol is illegal in Rishikesh and none is served, sold or brought in. Meat and eggs are not served either. For most people this turns out to be unremarkable after two days; for a few it is the hardest part of the week and it is better to know it is absolute rather than a preference.</p>
