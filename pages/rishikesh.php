          <h2>Where you stay</h2>
          <p>A ten-room guesthouse on the quiet side of the river, up a steep path. Single occupancy is standard here at no extra cost because the rooms are small. There is no lift and there are forty-one steps from the road.</p>
          <h2>The practice</h2>
          <p>Three hours from 06:00: an hour of pranayama and sitting, two hours of asana. Then nothing until an optional 17:00 session of chanting and philosophy, which about half the group attends and nobody is asked about.</p>
          <h2>Food</h2>
          <p>Three meals, all vegetarian, all at the guesthouse, all included. No alcohol is served in Tapovan and none is brought in &mdash; that is the law rather than our rule. No meat, no eggs, no onion or garlic in the ashram kitchen, which some people find is the hardest part of the week.</p>
        </div>
        <div class="prose">
          <h2>Getting there</h2>
          <p>Fly to Delhi, then either the overnight train to Haridwar (about six hours) or a car (about seven). We book a shared car from Delhi airport for anybody who wants one; it is $45 each and it leaves twice on the arrival day.</p>
          <h2>Weather, honestly</h2>
          <p>18-28C in late March, cold at 6am on the roof and warm by ten. Bring something with sleeves for the morning and something you can cover your shoulders with for the temples.</p>
          <h2>Who it suits</h2>
          <p>People who want the most traditional and the most demanding of the three weeks. Three hours of practice before breakfast is not a holiday, and the week is dry, vegetarian and early. Most of the people who book it have been before.</p>
