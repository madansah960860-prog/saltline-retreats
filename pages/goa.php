        <h2>What the roof is like</h2>
        <p>The practice space is the flat roof of the guesthouse, shaded by a woven palm canopy that goes up the day before we arrive and comes down the day after we leave. It holds fourteen mats comfortably and we cap the group at twelve. By nine in the morning it is too hot to be up there, which is the entire reason the day is shaped the way it is.</p>
        <h2>Ashwem itself</h2>
        <p>Ashwem is the quiet end of North Goa. There is one road, a row of beach shacks, a small market twice a week and very little else. It is a twenty-minute scooter ride to Arambol if you want noise and an hour to Panjim if you want a city. Most people do neither and spend the week between the roof, the sea and a hammock.</p>
        <h2>The one thing people complain about</h2>
        <p>Dogs. There are a lot of beach dogs at Ashwem, they are friendly, and they will sit on your mat during the evening session. Nobody has ever been bitten and several people have come back mainly for the dogs, but if you are frightened of them it is worth knowing in advance.</p>
