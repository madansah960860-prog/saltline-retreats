          <h2>Where you stay</h2>
          <p>A twelve-room guesthouse two minutes from the sand, family-run since 1994. Rooms are simple, fan-cooled and have hot water in the morning. Four have air conditioning and cost $90 more for the week; we allocate them to whoever asks first.</p>
          <h2>The practice</h2>
          <p>Two hours on the roof at 07:00, every morning, before it gets hot. Led vinyasa for the first four days, self-practice with help on the last two. One evening session on the beach at 18:00 which is breath and rest rather than postures.</p>
          <h2>Food</h2>
          <p>Two meals. Breakfast after practice at about 09:30 and dinner at 20:00, both vegetarian, both cooked by the family who run the guesthouse. Lunch is on you and there are eleven shacks within a ten-minute walk, none of which we have any arrangement with.</p>
        </div>
        <div class="prose">
          <h2>Getting there</h2>
          <p>Fly to Goa Dabolim (GOI) or Manohar (GOX). Manohar is an hour closer. A taxi from either is 2,000-3,500 rupees and we will book one if you send your flight number. We do not include flights and we do not sell them.</p>
          <h2>Weather, honestly</h2>
          <p>28-32C in the day, low twenties at night, and it will not rain. The sea is warm and calm in February. It is genuinely hot on the roof by nine, which is why practice starts at seven.</p>
          <h2>Who it suits</h2>
          <p>People who want a warm, sociable, unstructured week with a strong morning practice and no obligations after it. It is the easiest of the three, and the one people bring a non-practising partner to.</p>
