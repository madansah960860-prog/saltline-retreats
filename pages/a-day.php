          <h2>The empty middle</h2>
          <p>Four and a half hours in the middle of every day with nothing
            scheduled is the single most deliberate decision in the timetable,
            and it is the one people query most before they come and mention
            most afterwards.</p>
          <p>A retreat packed with workshops, sound baths, cacao ceremonies and
            journalling sessions is a conference in a warm place. The value of
            a week like this is almost entirely in the hours where nothing is
            being done to you, and those hours have to be protected by not
            filling them.</p>
          <p>Some people sleep through all of it for the first three days. That
            is normal and it is usually the point.</p>
          <h2>What is compulsory</h2>
          <p>Nothing. Not the morning practice, not dinner, not the excursion.
            Nobody takes a register and nobody will ask where you were. Several
            people each year disappear for two days in the middle of the week
            and come back, and that is a completely reasonable way to spend the
            time.</p>
        </div>
        <div class="prose">
          <h2>What the practice is</h2>
          <p>Mixed-level vinyasa in Goa and Bali, and a more traditional
            hatha-and-pranayama structure in Rishikesh. All three assume you
            have practised before but none of them assumes you are strong or
            flexible. There is no level test, no streaming, and no separate
            beginners' group.</p>
          <p>The first half of each week is led. The second half moves towards
            self-practice with individual help, which is the part most people
            find changes something: being in a room where you choose what to do
            next, with somebody good watching, is a different experience from
            following a class.</p>
          <h2>Silence</h2>
          <p>There is none imposed. We do not run silent retreats, there is no
            noble-silence morning, and nobody will ask you not to talk at
            breakfast. If you want a quiet week you will get one by simply
            being quiet, which is how it works everywhere else.</p>
        </div>
