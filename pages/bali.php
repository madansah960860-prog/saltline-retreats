        <h2>Why Amed and not Ubud</h2>
        <p>Ubud is where almost every Bali retreat happens and it is, at this point, a yoga industry with a town attached. Amed is three hours east, on the dry side of the island, and it is a fishing village with black sand and good diving. It is considerably less convenient and that is the point.</p>
        <h2>The water</h2>
        <p>The bay is deep, calm and clear, with coral about forty metres out and a wreck a short boat ride north. Snorkels and masks are at the bungalows and free to use. Two people every year end up diving instead of doing the afternoon session, which we regard as a reasonable trade.</p>
        <h2>The afternoon session</h2>
        <p>Ninety minutes at half four, propped, slow, and much more hands-on than the morning. It is where the shoulders get taken apart, where people finally understand what their hips are doing, and where the actual teaching of the week happens. It is also entirely optional and about three quarters of the group comes.</p>
