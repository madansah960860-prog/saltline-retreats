          <h2>Where you stay</h2>
          <p>Seven two-room bungalows on a terrace above a black sand bay, fifteen minutes' walk from the village. Each has a fan, a mosquito net and an outdoor shower. Two bungalows are on the flat; the rest are up steps.</p>
          <h2>The practice</h2>
          <p>Two hours at 07:00 and, uniquely among our three, ninety minutes at 16:30. The afternoon session is the reason this retreat exists: it is slower, propped, and where most of the actual teaching happens.</p>
          <h2>Food</h2>
          <p>Breakfast and dinner, mostly Balinese, cooked by two sisters from the village who have fed every group since 2019. Fish twice a week for anybody who wants it; everything else is vegetarian and most of it is vegan without trying.</p>
        </div>
        <div class="prose">
          <h2>Getting there</h2>
          <p>Fly to Denpasar (DPS). Amed is a three-hour drive east and the road is slow. We run one included minibus that meets the group at 14:00 on the arrival day; if you miss it, a private car is about 600,000 rupiah.</p>
          <h2>Weather, honestly</h2>
          <p>27-31C, humid, with a chance of an hour of rain in the late afternoon in September. The sea here is calm, deep and excellent for swimming, and there is coral forty metres from the beach.</p>
          <h2>Who it suits</h2>
          <p>People who want teaching rather than a timetable. Two sessions a day is more practice than Goa and less than Rishikesh, but the afternoon session means you leave having actually learned something specific.</p>
        </div>
