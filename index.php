        <h2>Who runs it and how small it is</h2>
      </div>
      <div class="prose">
        <p>Saltline is Tess Marlowe and, on each retreat, one local partner who
          has worked with us for years. There is no office of twelve people and
          no parent company. Tess teaches every morning session on every
          retreat, which is the main reason there are only three a year.</p>
        <p>Groups are capped at twelve, ten and fourteen, and those caps are
          real: we have turned people away from Goa in each of the last four
          years rather than putting a fifteenth mat on the roof. If a retreat
          is full the page says so, and we keep a list rather than pretending
          there is space.</p>
        <p>Places are held with a $300 deposit that is fully refundable for
          fourteen days, and the balance is not due until eight weeks before
          departure. There is no instalment plan with interest attached, no
          third-party finance, and nobody will chase you.</p>
        <p>We have run these weeks since 2018 and have cancelled twice &mdash;
          once for a cyclone and once when Tess broke a wrist. Both times
          everybody was refunded in full, including deposits, inside a
          fortnight. We do not issue credit notes in place of refunds and we
          are not going to start.</p>
        <p>Every retreat is capped, and the caps are the reason the weeks work
          rather than a scarcity tactic. Twelve on a roof in Goa is comfortable
          and fifteen is not; ten in the Rishikesh room is the number of mats
          that fit; fourteen is the number of beds at Amed.</p>
