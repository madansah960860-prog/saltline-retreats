            advertising-related sharing, use the cookie banner or the vendor
            opt-outs listed above, or email us with the subject line &ldquo;Do
            Not Sell or Share My Personal Information&rdquo;. We will confirm
            within ten business days and act within forty-five.</p>

          <h2>Children</h2>
          <p>This site is intended for adults. In line with the Children&rsquo;s
            Online Privacy Protection Act (COPPA), we do not knowingly collect
            personal information from children under 13, and we do not direct
            any part of this site or its advertising to children. Our retreats are for adults only; nobody under 18 travels with us. If
