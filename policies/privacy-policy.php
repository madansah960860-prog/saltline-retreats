            biometrics, religion, ethnicity, political opinion, sexual
            orientation &mdash; and you should not send it to us in a contact
            form. Booking a retreat means telling us health information &mdash; injuries, conditions, medication, dietary needs. We need it to teach you safely and to feed you. It is held in one mailbox, shared only with the guesthouse kitchen where a dietary requirement makes that necessary, and deleted twelve months after the retreat ends.</p>

