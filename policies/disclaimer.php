          <h2>Consult a physician first</h2>
          <p>Speak to your GP, physiotherapist, midwife or consultant before
            starting yoga or any new physical activity, and particularly before
            following anything described on this website, if any of the
            following apply to you: you are pregnant or have given birth within
            the last six months; you have high or low blood pressure, heart
            disease, or have had a cardiac event; you have glaucoma, a detached
            retina or recent eye surgery; you have osteoporosis, osteopenia or a
            history of fracture; you have a disc injury, spinal condition, or
