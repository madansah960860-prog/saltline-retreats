          <h2>Practise within your limits</h2>
          <p>The single most useful instruction in yoga is also the least
            glamorous: stop before you need to. Postures should be challenging,
            not painful. There is no version of a shape that is worth an injury,
            and there is no benefit that arrives only at the end range of a
            joint.</p>
          <p>Specifically: <strong>stop immediately</strong> and seek medical
            help if you experience chest pain or tightness, breathlessness out
            of proportion to the effort, dizziness or faintness, palpitations,
            sudden or severe pain, numbness, pins and needles, shooting pain
            down an arm or leg, or any loss of strength in a limb. Nerve
            symptoms are never something to breathe through. Do not continue on
            the assumption that a sensation will &ldquo;open&rdquo;.</p>
          <p>Pain that arrives during a posture is information. Pain that is
            still there the next day is a reason to stop and get advice. Neither
            is a sign of progress and neither should be pushed through.</p>

          <h2>Written material cannot supervise you</h2>
          <p>A sequence described in an article, however carefully written, has
            no idea what your body is doing. It cannot see that your back knee
            has collapsed inward, that you are gripping your jaw, or that the
            shape you think you are making is not the shape you are making. Any
            practice you follow from this website is undertaken entirely at your
            own risk, and you are responsible for your own safety while doing
            it.</p>
          <p>If you are new to yoga, learn in a room with a qualified teacher in
            it before you practise alone from written instructions. If you have
            an existing injury, work one-to-one with a teacher who knows about
            it, and tell them before the class rather than after.</p>

          <h2>No medical claims</h2>
          <p>We do not claim, and you should not infer, that yoga cures,
            treats, prevents or alleviates any disease or medical condition. We
            do not make claims about fertility, cancer, depression, immune
            function, detoxification, hormone balance or any similar subject.
            Where research exists on a specific effect &mdash; for example the
            well-documented relationship between slow breathing and heart-rate
            variability &mdash; we describe it as what it is: a measured effect,
            with limits, not a treatment.</p>
          <p>Never disregard professional medical advice, or delay seeking it,
            because of something you have read here. If you think you may have a
            medical emergency, call your local emergency number immediately.</p>

          <h2>Pregnancy and the post-natal period</h2>
          <p>Pregnancy changes what is appropriate, and it changes it
            differently in each trimester and for each person. Do not follow
            general-audience sequences from this or any website while pregnant.
            Tell your teacher before class, work with someone trained in
            pre-natal practice, and follow your midwife&rsquo;s or
            obstetrician&rsquo;s guidance over anything published here.</p>

