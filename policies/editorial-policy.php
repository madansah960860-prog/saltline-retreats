          <h1>Editorial policy</h1>
          <p class="%(L)s">Who writes what you read here, how it is checked
            before it goes up, and what happens when we get something
            wrong.</p>
          <p><strong>Effective date:</strong> %(EFF)s.</p>

          <h2>Who writes it</h2>
          <p>Everything on this site is written by Tess Marlowe, who teaches every retreat, and every practical detail &mdash; prices, transfers, meals, walking distances &mdash; is confirmed with the guesthouse in each country before the page goes up. Every article carries the name of the person who
            wrote it and the date it was published. We do not publish anonymous
            articles, we do not use a house byline to disguise who wrote
            something, and we do not publish material generated automatically
            and passed off as a person&rsquo;s work.</p>
          <p>We do not accept guest posts, sponsored articles or contributed
            content from outside. Every offer of a &ldquo;guest
            contribution&rdquo; we receive is an attempt to place a commercial
            link, and they are deleted.</p>

          <h2>How it is researched</h2>
          <p>Practical material &mdash; how a class runs, what a sequence
            contains, what to expect in your first month &mdash; comes from
            direct teaching experience in this room, and we say so rather than
            dressing it up as research.</p>
          <p>Where an article touches on anatomy, physiology or evidence, we
            work from textbooks and peer-reviewed literature rather than from
            other blogs, and we describe findings at the strength the evidence
            actually supports. If a result comes from a small study, we say it
            comes from a small study. If the honest summary is &ldquo;this is
            widely taught and poorly evidenced&rdquo;, that is what we
            write.</p>
          <p>We avoid three things that are endemic in writing about yoga:
            anatomical claims that sound precise but are not testable; the
            confident restatement of an idea simply because it is traditional;
            and health claims that a regulator would take an interest in. If we
            cannot support a sentence, it does not go in.</p>

          <h2>How it is reviewed</h2>
          <p>Nothing is published by its author alone. Every article is read by
            at least one other teacher here before it goes up, checking three
            things: that the practical instructions are safe and correctly
            described, that no health claim has crept in unsupported, and that
            the piece says plainly where the limits of written instruction
            are.</p>
          <p>Anything touching on injury, pain, pregnancy, breathing practice or
            a medical condition gets an additional read specifically for safety
            language, and carries an explicit note pointing the reader to a
            clinician. Our <a href="disclaimer.php">disclaimer</a> sets out the
            substance of that.</p>

          <h2>Updates and corrections</h2>
          <p>Articles are dated and we review the practical ones at least once a
            year. Where an article has been substantially revised we add a
            revision date; where a correction has been made to a fact or an
            instruction, we say what was corrected rather than quietly editing
            the page.</p>
          <p>We do not delete articles to hide a mistake, and we do not
            back-date anything. If a piece is withdrawn entirely, the page stays
            up with an explanation of why.</p>

          <h2>Asking for a correction</h2>
          <p>Email <a href="mailto:%(E)s">%(E)s</a> with the page address and
            what you believe is wrong. You do not need to be polite about it and
            you do not need to prove your credentials. We aim to reply within
            five working days.</p>
          <p>If you are right, we fix it and note the correction on the page. If
            we think you are not, we will tell you why rather than ignore the
            message. If it is a matter of judgement rather than fact, we will
            say that, and we may add a note acknowledging the disagreement.
            Corrections about safety are treated as urgent and are acted on the
            same day.</p>

          <h2>Independence</h2>
          <p>Nothing on this site is written because somebody paid for it. No
            advertiser sees an article before publication and no advertiser has
            any right of approval over anything. The full detail of how the site
            is funded is in the
            <a href="advertising-disclosure.php">advertising
            disclosure</a>.</p>

